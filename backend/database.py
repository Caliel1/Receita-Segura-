# ---------- Linhas e conexão ----------

class Linha(dict):
    """Uma linha do resultado: acessa por nome (linha["nome"]) ou por posição (linha[0])."""

    def __getitem__(self, chave):
        if isinstance(chave, int):
            return list(self.values())[chave]
        return super().__getitem__(chave)


def _fabrica_linha(cursor):
    nomes = [coluna.name for coluna in cursor.description] if cursor.description else []
    return lambda valores: Linha(zip(nomes, valores))


class Conexao:
    """Envolve a conexão do psycopg: aceita `?` como marcador de parâmetro, como no SQLite."""

    def __init__(self, bruta: psycopg.Connection, pool: ConnectionPool | None = None):
        self._bruta = bruta
        self._pool = pool

    @staticmethod
    def _traduzir(sql: str) -> str:
        # O psycopg usa %s; um % literal no SQL precisa ser escrito %%.
        return sql.replace("%", "%%").replace("?", "%s")

    def execute(self, sql: str, parametros=()):
        return self._bruta.execute(self._traduzir(sql), tuple(parametros))

    def executemany(self, sql: str, linhas) -> None:
        with self._bruta.cursor() as cursor:
            cursor.executemany(self._traduzir(sql), [tuple(l) for l in linhas])

    def executar_script(self, script: str) -> None:
        """Vários comandos de uma vez, sem parâmetros (usado na criação das tabelas)."""
        self._bruta.execute(script)

    def close(self) -> None:
        if self._bruta is None:
            return
        if self._pool is not None:
            self._pool.putconn(self._bruta)  # devolve ao conjunto de conexões, não fecha
        else:
            self._bruta.close()
        self._bruta = None


_pool: ConnectionPool | None = None
_trava_pool = threading.Lock()


def _url_sem_senha() -> str:
    partes = urlsplit(DATABASE_URL)
    servidor = (partes.hostname or "(socket local)") + (f":{partes.port}" if partes.port else "")
    return f"{partes.scheme}://{partes.username or ''}:***@{servidor}{partes.path}"


def _obter_pool() -> ConnectionPool:
    """Cria (uma vez só) o conjunto de conexões reaproveitáveis. Conectar ao PostgreSQL a cada
    requisição seria lento, então mantemos algumas conexões abertas."""
    global _pool
    with _trava_pool:
        if _pool is None:
            pool = ConnectionPool(
                DATABASE_URL, min_size=1, max_size=10, open=False,
                kwargs={"autocommit": True, "row_factory": _fabrica_linha},
            )
            try:
                pool.open(wait=True, timeout=10)
            except PoolTimeout:
                pool.close()
                raise RuntimeError(
                    f"Não consegui conectar ao PostgreSQL em {_url_sem_senha()}.\n"
                    "Verifique se o servidor está ligado (veja o README, seção PostgreSQL) e se a variável "
                    "DATABASE_URL está correta."
                ) from None
            _pool = pool
        return _pool


def fechar_pool() -> None:
    global _pool
    with _trava_pool:
        if _pool is not None:
            _pool.close()
            _pool = None


def conectar() -> Conexao:
    pool = _obter_pool()
    return Conexao(pool.getconn(), pool)


def get_db():
    """Dependência do FastAPI: uma conexão (do conjunto) por requisição."""
    con = conectar()
    try:
        yield con
    finally:
        con.close()


# Todas as transações de escrita pegam esta mesma trava. Assim duas emissões ao mesmo tempo não
# calculam o mesmo número de receita/documento (o SQLite fazia isso sozinho com BEGIN IMMEDIATE).
TRAVA_ESCRITA = 7_246_001


@contextmanager
def transacao(con: Conexao):
    with con._bruta.transaction():  # BEGIN ... COMMIT (ou ROLLBACK se der erro)
        con._bruta.execute("SELECT pg_advisory_xact_lock(%s)", (TRAVA_ESCRITA,))
        yield


# Colunas acrescentadas depois da primeira versão — instalações antigas recebem via ALTER TABLE.
COLUNAS_NOVAS = {
    "usuarios": {"data_nascimento": "TEXT", "cpf": "TEXT", "telefone": "TEXT"},
}


def migrar(con: Conexao) -> None:
    for tabela, colunas in COLUNAS_NOVAS.items():
        for nome, tipo in colunas.items():
            con.executar_script(f"ALTER TABLE {tabela} ADD COLUMN IF NOT EXISTS {nome} {tipo}")


def criar_tabelas() -> None:
    con = conectar()
    try:
        con.executar_script(SCHEMA)
        migrar(con)
    finally:
        con.close()
